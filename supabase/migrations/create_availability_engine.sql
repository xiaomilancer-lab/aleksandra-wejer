set location_id = case
  when lower(coalesce(location, '')) like '%nowa wieś rzeczna%' or lower(coalesce(location, '')) like '%zielińscy%' then 'nowa-wies-rzeczna'
  when lower(coalesce(location, '')) like '%arthro%' then 'arthro-cure-clinic'
  else location_id
end
